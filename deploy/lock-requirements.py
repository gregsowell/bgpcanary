#!/usr/bin/env python3
"""Regenerate requirements.txt (exact versions + hashes) from a `pip freeze` of a tested install.

    ssh server '/opt/bgpcanary/venv/bin/pip freeze' > /tmp/freeze.txt
    python3 deploy/lock-requirements.py /tmp/freeze.txt > requirements.txt

Every file PyPI publishes for each pinned version is hashed, so the lock works on any CPU architecture, and
`pip install --require-hashes` (which the installer uses) refuses anything that isn't exactly those files.
Top-level dependencies and their minimum versions are listed in requirements.in.
"""
import json
import sys
import urllib.request

sys.stdout.reconfigure(newline="\n")   # LF even on Windows: pip reads the backslash continuations
lines = []
for raw in open(sys.argv[1], encoding="utf-8"):
    raw = raw.strip()
    if not raw or raw.startswith("#") or "==" not in raw:
        continue
    name, ver = raw.split("==", 1)
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=30) as r:
        files = json.load(r)["urls"]
    hashes = sorted({f["digests"]["sha256"] for f in files})
    if not hashes:
        sys.exit(f"{name}=={ver}: no files on PyPI")
    lines.append(f"{name.lower()}=={ver} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
print("# Generated by deploy/lock-requirements.py from a tested install; edit requirements.in, not this file.")
print("\n".join(sorted(lines)))
